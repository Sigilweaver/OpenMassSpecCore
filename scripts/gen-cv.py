#!/usr/bin/env python3
"""Generate src/cv/terms.rs from psi-ms.obo.

Reads the term list in scripts/cv-terms.txt (RUST_IDENT ACCESSION per line),
looks every accession up in the PSI-MS ontology, and writes one typed
`Term` constant per entry with the exact OBO name. The output header records
the OBO source URL, its data-version, and its SHA-256, so the generated file
is reproducible. The build never fetches anything; rerun this script and
commit the result to change the term set or the ontology version.

Usage:
    scripts/gen-cv.py                      # download --url (default below)
    scripts/gen-cv.py --obo psi-ms.obo     # use a local copy; --url still
                                           # names the source in the header

Fails when an accession is missing from the OBO or is marked obsolete, or
when two identifiers map to the same accession.
"""

import argparse
import hashlib
import re
import sys
import urllib.request
from pathlib import Path

DEFAULT_URL = "https://raw.githubusercontent.com/HUPO-PSI/psi-ms-CV/v4.2.4/psi-ms.obo"

ROOT = Path(__file__).resolve().parent.parent
TERM_LIST = ROOT / "scripts" / "cv-terms.txt"
OUT = ROOT / "src" / "cv" / "terms.rs"


def parse_obo(text):
    """Return (data_version, {accession: (name, obsolete)})."""
    version = None
    terms = {}
    acc = name = None
    obsolete = False
    in_term = False

    def flush():
        if in_term and acc is not None:
            terms[acc] = (name, obsolete)

    for line in text.splitlines():
        if version is None and line.startswith("data-version:"):
            version = line.split(":", 1)[1].strip()
        if line.startswith("["):
            flush()
            in_term = line.strip() == "[Term]"
            acc = name = None
            obsolete = False
        elif line.startswith("id: "):
            acc = line[4:].strip()
        elif line.startswith("name: "):
            name = line[6:].strip()
        elif line.startswith("is_obsolete: true"):
            obsolete = True
    flush()
    if version is None:
        sys.exit("no data-version header in the OBO")
    return version, terms


def read_term_list():
    entries = []
    for n, raw in enumerate(TERM_LIST.read_text().splitlines(), 1):
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        parts = line.split()
        if len(parts) != 2 or not re.fullmatch(r"[A-Z][A-Z0-9_]*", parts[0]):
            sys.exit(f"{TERM_LIST}:{n}: expected 'RUST_IDENT ACCESSION', got {raw!r}")
        if not re.fullmatch(r"(MS|UO):\d{7}", parts[1]):
            sys.exit(f"{TERM_LIST}:{n}: bad accession {parts[1]!r}")
        entries.append((parts[0], parts[1]))
    return entries


def rust_str(s):
    if not s.isascii() or any(c in s for c in '"\\') or any(ord(c) < 0x20 for c in s):
        sys.exit(f"term name {s!r} needs escaping; extend gen-cv.py")
    return f'"{s}"'


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--obo", help="local psi-ms.obo (default: download --url)")
    ap.add_argument("--url", default=DEFAULT_URL, help="OBO source URL")
    args = ap.parse_args()

    if args.obo:
        data = Path(args.obo).read_bytes()
    else:
        with urllib.request.urlopen(args.url) as resp:  # noqa: S310 (fixed https URL)
            data = resp.read()
    sha256 = hashlib.sha256(data).hexdigest()
    version, terms = parse_obo(data.decode("utf-8"))

    entries = read_term_list()
    seen_ident, seen_acc, problems = set(), set(), []
    for ident, acc in entries:
        if ident in seen_ident:
            problems.append(f"duplicate identifier {ident}")
        if acc in seen_acc:
            problems.append(f"duplicate accession {acc}")
        seen_ident.add(ident)
        seen_acc.add(acc)
        if acc not in terms:
            problems.append(f"{ident}: {acc} not in the OBO")
        elif terms[acc][1]:
            problems.append(f"{ident}: {acc} is obsolete")
        elif not terms[acc][0]:
            problems.append(f"{ident}: {acc} has no name")
    if problems:
        sys.exit("\n".join(problems))

    out = []
    out.append("// @generated by scripts/gen-cv.py from scripts/cv-terms.txt. Do not edit by hand.")
    out.append(f"// Source: {args.url}")
    out.append(f"// data-version: {version}")
    out.append(f"// sha256: {sha256}")
    out.append("")
    out.append("use super::Term;")
    out.append("")
    def str_const(name, value):
        # Match rustfmt: wrap after `=` when the line exceeds 100 columns.
        line = f"pub const {name}: &str = {rust_str(value)};"
        if len(line) <= 100:
            return [line]
        return [f"pub const {name}: &str =", f"    {rust_str(value)};"]

    out.append("/// `data-version` of the psi-ms.obo these terms were generated from.")
    out.extend(str_const("PSI_MS_VERSION", version))
    out.append("")
    out.append("/// URL of the psi-ms.obo these terms were generated from.")
    out.extend(str_const("PSI_MS_SOURCE_URL", args.url))
    for ident, acc in entries:
        name = terms[acc][0]
        out.append("")
        out.append(f"/// `{acc}` {name}.")
        out.append(f"pub const {ident}: Term = Term {{")
        out.append(f"    accession: {rust_str(acc)},")
        out.append(f"    name: {rust_str(name)},")
        out.append("};")
    out.append("")
    out.append("/// Every generated term, in `scripts/cv-terms.txt` order.")
    out.append("pub const ALL: &[Term] = &[")
    for ident, _ in entries:
        out.append(f"    {ident},")
    out.append("];")
    out.append("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT.relative_to(ROOT)} ({len(entries)} terms, psi-ms.obo {version})")


if __name__ == "__main__":
    main()
